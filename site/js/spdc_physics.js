/**
 * spdc_physics.js
 * =================
 * Shared browser-side physics for the SPDC coincidence-analysis dashboards.
 *
 * Single source of truth for the *analytic* closed form, mirroring the
 * Python `spdc` package (spdc.closedform). Every dashboard page loads this
 * module and calls window.SPDC.* — no page re-declares the physics.
 *
 * System: type-II SPDC two-mode squeezed vacuum (TMSV) in H/V modes,
 * rotated by a HWP at angle theta, split at a PBS, measured by two lossy
 * bucket (click / no-click) detectors.
 *
 *   lam        squeezing parameter, |lam| < 1  (tanh r)
 *   etaH,etaV  total detection efficiency of the H / V arm, in [0, 1]
 *   theta      HWP angle; the coincidence dip sits at theta = pi/8
 *   phi        optical phase phi = 4*theta  (used for Fisher information)
 *
 * The Fisher expressions p11/p20/p02 and their theta-derivatives are
 * generated by sympy.jscode from the exact same symbolic closed form used
 * in spdc.closedform._build_fisher(), so JS and Python agree to machine
 * precision.
 */
(function (root) {
  "use strict";

  var EPS = 1e-15;

  // ---- Joint no-click probability P(0,0) -------------------------------
  function p00(lam, etaH, etaV, theta) {
    var tH = 1 - etaH, tV = 1 - etaV;
    var num = 1 - lam * lam;
    var t1 = 1 - lam * lam * tH * tV;
    var rad = t1 * t1
      - lam * lam * (etaH - etaV) * (etaH - etaV) * Math.pow(Math.sin(4 * theta), 2);
    return num / Math.sqrt(Math.max(rad, EPS));
  }

  // ---- Single-arm no-click: opposite detector transparent (eta = 0) ----
  function marginalNoclick(lam, eta, theta, arm) {
    if (arm === "H") return p00(lam, eta, 0, theta); // only H can click
    if (arm === "V") return p00(lam, 0, eta, theta); // only V can click
    throw new Error("arm must be 'H' or 'V'");
  }

  // ---- Coincidence via inclusion-exclusion -----------------------------
  function coincidence(lam, etaH, etaV, theta) {
    var P00 = p00(lam, etaH, etaV, theta);
    var PH0 = p00(lam, etaH, 0, theta); // only H can click
    var PV0 = p00(lam, 0, etaV, theta); // only V can click
    return 1 - PH0 - PV0 + P00;
  }

  // ---- P_click = 1 - P(0,0) --------------------------------------------
  function clickProbability(lam, etaH, etaV, theta) {
    return 1 - p00(lam, etaH, etaV, theta);
  }

  // ---- Derived observables ---------------------------------------------
  function linspace(start, stop, num) {
    var arr = new Array(num);
    var step = (stop - start) / (num - 1);
    for (var i = 0; i < num; i++) arr[i] = start + step * i;
    return arr;
  }

  // Interference visibility V = (Cmax - Cmin)/(Cmax + Cmin) over
  // theta in [0, pi/4]. Cmax at theta=0, Cmin at theta=pi/8.
  function visibility(lam, etaH, etaV) {
    var Cmax = coincidence(lam, etaH, etaV, 0);
    var Cmin = coincidence(lam, etaH, etaV, Math.PI / 8);
    return (Cmax - Cmin) / (Cmax + Cmin);
  }

  // Multi-pair visibility ceiling for perfect detectors.
  function visibilityIdeal(lam) { return Math.sqrt(1 - lam * lam); }

  // Mean photon pairs per mode.
  function nbarPerMode(lam) { return lam * lam / (1 - lam * lam); }

  // ---- Fisher information for phi = 4*theta -----------------------------
  // p11/p20/p02 are the click-conditioned outcome probabilities and
  // dp** their d/dtheta derivatives. Bodies emitted by sympy.jscode from
  // spdc.closedform._build_fisher() (variables: lam, etaH, etaV, th).
  function p11(lam, etaH, etaV, th) { return ((1 - Math.pow(lam, 2))/Math.sqrt(-Math.pow(lam, 2)*Math.pow(etaH - etaV, 2)*Math.pow(Math.sin(4*th), 2) + Math.pow(-Math.pow(lam, 2)*(1 - etaH)*(1 - etaV) + 1, 2)) - (1 - Math.pow(lam, 2))/Math.sqrt(-Math.pow(etaV, 2)*Math.pow(lam, 2)*Math.pow(Math.sin(4*th), 2) + Math.pow(-Math.pow(lam, 2)*(1 - etaV) + 1, 2)) - (1 - Math.pow(lam, 2))/Math.sqrt(-Math.pow(etaH, 2)*Math.pow(lam, 2)*Math.pow(Math.sin(4*th), 2) + Math.pow(-Math.pow(lam, 2)*(1 - etaH) + 1, 2)) + 1)/(-(1 - Math.pow(lam, 2))/Math.sqrt(-Math.pow(lam, 2)*Math.pow(etaH - etaV, 2)*Math.pow(Math.sin(4*th), 2) + Math.pow(-Math.pow(lam, 2)*(1 - etaH)*(1 - etaV) + 1, 2)) + 1); }
  function p20(lam, etaH, etaV, th) { return (-(1 - Math.pow(lam, 2))/Math.sqrt(-Math.pow(lam, 2)*Math.pow(etaH - etaV, 2)*Math.pow(Math.sin(4*th), 2) + Math.pow(-Math.pow(lam, 2)*(1 - etaH)*(1 - etaV) + 1, 2)) + (1 - Math.pow(lam, 2))/Math.sqrt(-Math.pow(etaV, 2)*Math.pow(lam, 2)*Math.pow(Math.sin(4*th), 2) + Math.pow(-Math.pow(lam, 2)*(1 - etaV) + 1, 2)))/(-(1 - Math.pow(lam, 2))/Math.sqrt(-Math.pow(lam, 2)*Math.pow(etaH - etaV, 2)*Math.pow(Math.sin(4*th), 2) + Math.pow(-Math.pow(lam, 2)*(1 - etaH)*(1 - etaV) + 1, 2)) + 1); }
  function p02(lam, etaH, etaV, th) { return (-(1 - Math.pow(lam, 2))/Math.sqrt(-Math.pow(lam, 2)*Math.pow(etaH - etaV, 2)*Math.pow(Math.sin(4*th), 2) + Math.pow(-Math.pow(lam, 2)*(1 - etaH)*(1 - etaV) + 1, 2)) + (1 - Math.pow(lam, 2))/Math.sqrt(-Math.pow(etaH, 2)*Math.pow(lam, 2)*Math.pow(Math.sin(4*th), 2) + Math.pow(-Math.pow(lam, 2)*(1 - etaH) + 1, 2)))/(-(1 - Math.pow(lam, 2))/Math.sqrt(-Math.pow(lam, 2)*Math.pow(etaH - etaV, 2)*Math.pow(Math.sin(4*th), 2) + Math.pow(-Math.pow(lam, 2)*(1 - etaH)*(1 - etaV) + 1, 2)) + 1); }
  function dp11(lam, etaH, etaV, th) { return 4*Math.pow(lam, 2)*(1 - Math.pow(lam, 2))*Math.pow(etaH - etaV, 2)*((1 - Math.pow(lam, 2))/Math.sqrt(-Math.pow(lam, 2)*Math.pow(etaH - etaV, 2)*Math.pow(Math.sin(4*th), 2) + Math.pow(-Math.pow(lam, 2)*(1 - etaH)*(1 - etaV) + 1, 2)) - (1 - Math.pow(lam, 2))/Math.sqrt(-Math.pow(etaV, 2)*Math.pow(lam, 2)*Math.pow(Math.sin(4*th), 2) + Math.pow(-Math.pow(lam, 2)*(1 - etaV) + 1, 2)) - (1 - Math.pow(lam, 2))/Math.sqrt(-Math.pow(etaH, 2)*Math.pow(lam, 2)*Math.pow(Math.sin(4*th), 2) + Math.pow(-Math.pow(lam, 2)*(1 - etaH) + 1, 2)) + 1)*Math.sin(4*th)*Math.cos(4*th)/(Math.pow(-(1 - Math.pow(lam, 2))/Math.sqrt(-Math.pow(lam, 2)*Math.pow(etaH - etaV, 2)*Math.pow(Math.sin(4*th), 2) + Math.pow(-Math.pow(lam, 2)*(1 - etaH)*(1 - etaV) + 1, 2)) + 1, 2)*Math.pow(-Math.pow(lam, 2)*Math.pow(etaH - etaV, 2)*Math.pow(Math.sin(4*th), 2) + Math.pow(-Math.pow(lam, 2)*(1 - etaH)*(1 - etaV) + 1, 2), 3/2)) + (-4*Math.pow(etaH, 2)*Math.pow(lam, 2)*(1 - Math.pow(lam, 2))*Math.sin(4*th)*Math.cos(4*th)/Math.pow(-Math.pow(etaH, 2)*Math.pow(lam, 2)*Math.pow(Math.sin(4*th), 2) + Math.pow(-Math.pow(lam, 2)*(1 - etaH) + 1, 2), 3/2) - 4*Math.pow(etaV, 2)*Math.pow(lam, 2)*(1 - Math.pow(lam, 2))*Math.sin(4*th)*Math.cos(4*th)/Math.pow(-Math.pow(etaV, 2)*Math.pow(lam, 2)*Math.pow(Math.sin(4*th), 2) + Math.pow(-Math.pow(lam, 2)*(1 - etaV) + 1, 2), 3/2) + 4*Math.pow(lam, 2)*(1 - Math.pow(lam, 2))*Math.pow(etaH - etaV, 2)*Math.sin(4*th)*Math.cos(4*th)/Math.pow(-Math.pow(lam, 2)*Math.pow(etaH - etaV, 2)*Math.pow(Math.sin(4*th), 2) + Math.pow(-Math.pow(lam, 2)*(1 - etaH)*(1 - etaV) + 1, 2), 3/2))/(-(1 - Math.pow(lam, 2))/Math.sqrt(-Math.pow(lam, 2)*Math.pow(etaH - etaV, 2)*Math.pow(Math.sin(4*th), 2) + Math.pow(-Math.pow(lam, 2)*(1 - etaH)*(1 - etaV) + 1, 2)) + 1); }
  function dp20(lam, etaH, etaV, th) { return 4*Math.pow(lam, 2)*(1 - Math.pow(lam, 2))*Math.pow(etaH - etaV, 2)*(-(1 - Math.pow(lam, 2))/Math.sqrt(-Math.pow(lam, 2)*Math.pow(etaH - etaV, 2)*Math.pow(Math.sin(4*th), 2) + Math.pow(-Math.pow(lam, 2)*(1 - etaH)*(1 - etaV) + 1, 2)) + (1 - Math.pow(lam, 2))/Math.sqrt(-Math.pow(etaV, 2)*Math.pow(lam, 2)*Math.pow(Math.sin(4*th), 2) + Math.pow(-Math.pow(lam, 2)*(1 - etaV) + 1, 2)))*Math.sin(4*th)*Math.cos(4*th)/(Math.pow(-(1 - Math.pow(lam, 2))/Math.sqrt(-Math.pow(lam, 2)*Math.pow(etaH - etaV, 2)*Math.pow(Math.sin(4*th), 2) + Math.pow(-Math.pow(lam, 2)*(1 - etaH)*(1 - etaV) + 1, 2)) + 1, 2)*Math.pow(-Math.pow(lam, 2)*Math.pow(etaH - etaV, 2)*Math.pow(Math.sin(4*th), 2) + Math.pow(-Math.pow(lam, 2)*(1 - etaH)*(1 - etaV) + 1, 2), 3/2)) + (4*Math.pow(etaV, 2)*Math.pow(lam, 2)*(1 - Math.pow(lam, 2))*Math.sin(4*th)*Math.cos(4*th)/Math.pow(-Math.pow(etaV, 2)*Math.pow(lam, 2)*Math.pow(Math.sin(4*th), 2) + Math.pow(-Math.pow(lam, 2)*(1 - etaV) + 1, 2), 3/2) - 4*Math.pow(lam, 2)*(1 - Math.pow(lam, 2))*Math.pow(etaH - etaV, 2)*Math.sin(4*th)*Math.cos(4*th)/Math.pow(-Math.pow(lam, 2)*Math.pow(etaH - etaV, 2)*Math.pow(Math.sin(4*th), 2) + Math.pow(-Math.pow(lam, 2)*(1 - etaH)*(1 - etaV) + 1, 2), 3/2))/(-(1 - Math.pow(lam, 2))/Math.sqrt(-Math.pow(lam, 2)*Math.pow(etaH - etaV, 2)*Math.pow(Math.sin(4*th), 2) + Math.pow(-Math.pow(lam, 2)*(1 - etaH)*(1 - etaV) + 1, 2)) + 1); }
  function dp02(lam, etaH, etaV, th) { return 4*Math.pow(lam, 2)*(1 - Math.pow(lam, 2))*Math.pow(etaH - etaV, 2)*(-(1 - Math.pow(lam, 2))/Math.sqrt(-Math.pow(lam, 2)*Math.pow(etaH - etaV, 2)*Math.pow(Math.sin(4*th), 2) + Math.pow(-Math.pow(lam, 2)*(1 - etaH)*(1 - etaV) + 1, 2)) + (1 - Math.pow(lam, 2))/Math.sqrt(-Math.pow(etaH, 2)*Math.pow(lam, 2)*Math.pow(Math.sin(4*th), 2) + Math.pow(-Math.pow(lam, 2)*(1 - etaH) + 1, 2)))*Math.sin(4*th)*Math.cos(4*th)/(Math.pow(-(1 - Math.pow(lam, 2))/Math.sqrt(-Math.pow(lam, 2)*Math.pow(etaH - etaV, 2)*Math.pow(Math.sin(4*th), 2) + Math.pow(-Math.pow(lam, 2)*(1 - etaH)*(1 - etaV) + 1, 2)) + 1, 2)*Math.pow(-Math.pow(lam, 2)*Math.pow(etaH - etaV, 2)*Math.pow(Math.sin(4*th), 2) + Math.pow(-Math.pow(lam, 2)*(1 - etaH)*(1 - etaV) + 1, 2), 3/2)) + (4*Math.pow(etaH, 2)*Math.pow(lam, 2)*(1 - Math.pow(lam, 2))*Math.sin(4*th)*Math.cos(4*th)/Math.pow(-Math.pow(etaH, 2)*Math.pow(lam, 2)*Math.pow(Math.sin(4*th), 2) + Math.pow(-Math.pow(lam, 2)*(1 - etaH) + 1, 2), 3/2) - 4*Math.pow(lam, 2)*(1 - Math.pow(lam, 2))*Math.pow(etaH - etaV, 2)*Math.sin(4*th)*Math.cos(4*th)/Math.pow(-Math.pow(lam, 2)*Math.pow(etaH - etaV, 2)*Math.pow(Math.sin(4*th), 2) + Math.pow(-Math.pow(lam, 2)*(1 - etaH)*(1 - etaV) + 1, 2), 3/2))/(-(1 - Math.pow(lam, 2))/Math.sqrt(-Math.pow(lam, 2)*Math.pow(etaH - etaV, 2)*Math.pow(Math.sin(4*th), 2) + Math.pow(-Math.pow(lam, 2)*(1 - etaH)*(1 - etaV) + 1, 2)) + 1); }

  // F_phi at a single phi.  F_phi = F_theta / 16  (theta = phi/4).
  function fisherPhi(lam, etaH, etaV, phi) {
    var th = phi / 4;
    var pairs = [
      [p11(lam, etaH, etaV, th), dp11(lam, etaH, etaV, th)],
      [p20(lam, etaH, etaV, th), dp20(lam, etaH, etaV, th)],
      [p02(lam, etaH, etaV, th), dp02(lam, etaH, etaV, th)]
    ];
    var Ftheta = 0;
    for (var i = 0; i < pairs.length; i++) {
      var p = pairs[i][0], dp = pairs[i][1];
      if (p > EPS) Ftheta += dp * dp / p;
    }
    return Ftheta / 16;
  }

  // Shot-noise limit F_SNL = n_bar / P_click, n_bar = 2 lam^2/(1-lam^2).
  function snlPhi(lam, etaH, etaV, phi) {
    var th = phi / 4;
    var nMean = 2 * lam * lam / (1 - lam * lam);
    return nMean / clickProbability(lam, etaH, etaV, th);
  }

  // ======================================================================
  //  Truncated Fock-space ("brute force") engine
  // ----------------------------------------------------------------------
  //  Browser twin of spdc.fock_numpy / spdc.fock_qutip. The two-mode state
  //  |Psi> = sqrt(1-lam^2) exp(lam K^dag)|0,0> is stored as a REAL vector of
  //  length N*N with flat index  idx = nH*N + nV  (H = outer, V = inner).
  //  All operators are real because c, s, lam are real, so a single
  //  Float64Array suffices.
  //
  //  Truncating both modes at N Fock states caps the representable photon
  //  number: at large lam the true photon-number distribution has weight
  //  above N and that weight is discarded, so the Fock result drifts away
  //  from the (truncation-free) closed form. This is the whole pedagogical
  //  point of the NumPy dashboard — N is the wall, the closed form has none.
  //
  //  Creation operators (Fock ladder):
  //    a_H^dag |nH,nV> = sqrt(nH+1) |nH+1,nV>
  //    a_V^dag |nH,nV> = sqrt(nV+1) |nH,nV+1>
  //  K^dag = (c a_H^dag + s a_V^dag)(s a_H^dag - c a_V^dag),  c=cos2t, s=sin2t
  // ----------------------------------------------------------------------

  // out += s * (a_H^dag v)   (in place accumulate; scale s)
  function addAHdag(out, v, N, scale) {
    for (var nH = 0; nH < N - 1; nH++) {
      var g = Math.sqrt(nH + 1) * scale;
      var srcRow = nH * N, dstRow = (nH + 1) * N;
      for (var nV = 0; nV < N; nV++) out[dstRow + nV] += g * v[srcRow + nV];
    }
  }
  // out += s * (a_V^dag v)
  function addAVdag(out, v, N, scale) {
    for (var nH = 0; nH < N; nH++) {
      var row = nH * N;
      for (var nV = 0; nV < N - 1; nV++) {
        out[row + nV + 1] += Math.sqrt(nV + 1) * scale * v[row + nV];
      }
    }
  }

  // K^dag applied to state vector v -> new Float64Array
  function applyKdag(v, N, c, s) {
    var inner = new Float64Array(N * N);   // (s a_H^dag - c a_V^dag) v
    addAHdag(inner, v, N, s);
    addAVdag(inner, v, N, -c);
    var out = new Float64Array(N * N);     // (c a_H^dag + s a_V^dag) inner
    addAHdag(out, inner, N, c);
    addAVdag(out, inner, N, s);
    return out;
  }

  // |Psi> = sqrt(1-lam^2) * sum_{n=0}^{nmax-1} (lam^n / n!) (K^dag)^n |0,0>.
  //
  // IMPORTANT: this multiplies by the EXACT analytic prefactor
  // sqrt(1-lam^2) and does NOT renormalize the truncated vector. In a
  // truncated Fock space the series loses the probability weight that lives
  // above N photons, so the resulting state has norm slightly below one —
  // and that missing weight IS the truncation error we want to expose.
  // Renormalizing to unit norm would silently redistribute it and hide the
  // divergence. This mirrors spdc.fock_numpy.brute_P00 exactly (psi = Lam *
  // acc, no renormalization), so the browser engine is a faithful twin.
  function fockState(lam, theta, N, nmax) {
    var c = Math.cos(2 * theta), s = Math.sin(2 * theta);
    var Lam = Math.sqrt(1.0 - lam * lam);
    var dim = N * N;
    var acc = new Float64Array(dim);
    var term = new Float64Array(dim);
    term[0] = 1.0;                          // vacuum |0,0>, power 0
    for (var n = 0; n < nmax; n++) {        // accumulate powers 0 .. nmax-1
      for (var i = 0; i < dim; i++) acc[i] += term[i];
      term = applyKdag(term, N, c, s);
      var scale = lam / (n + 1);
      for (var j = 0; j < dim; j++) term[j] *= scale;
    }
    for (var k = 0; k < dim; k++) acc[k] *= Lam;
    return acc;
  }

  // Coincidence from the truncated Fock state. The state depends only on
  // (lam, theta, N, nmax) — NOT on the efficiencies — so it is built once
  // and reused for the three weighted no-click sums (inclusion-exclusion).
  function fockCoincidence(lam, etaH, etaV, theta, N, nmax) {
    if (N === undefined) N = 60;
    if (nmax === undefined) nmax = 45;
    var psi = fockState(lam, theta, N, nmax);
    var tH = 1 - etaH, tV = 1 - etaV;
    var P00 = 0.0, PH0 = 0.0, PV0 = 0.0;
    // precompute per-index photon numbers implicitly via row/col loops
    for (var nH = 0; nH < N; nH++) {
      var wH = Math.pow(tH, nH);          // (1-etaH)^nH
      var row = nH * N;
      for (var nV = 0; nV < N; nV++) {
        var a = psi[row + nV];
        var p = a * a;
        if (p === 0) continue;
        var wV = Math.pow(tV, nV);        // (1-etaV)^nV
        P00 += p * wH * wV;               // both detectors lossy
        PH0 += p * wH;                    // etaV = 0  -> tV = 1
        PV0 += p * wV;                    // etaH = 0  -> tH = 1
      }
    }
    return 1 - PH0 - PV0 + P00;
  }

  // Sample the Fock coincidence at an array of theta values (marker set),
  // returning normalized values C/Cmax where Cmax is the closed-form peak
  // over [0, pi/4] (so markers share the closed curve's normalization).
  function fockCoincidenceCurve(lam, etaH, etaV, thetas, N, nmax, cmax) {
    var out = new Array(thetas.length);
    for (var i = 0; i < thetas.length; i++) {
      out[i] = fockCoincidence(lam, etaH, etaV, thetas[i], N, nmax) / cmax;
    }
    return out;
  }

  root.SPDC = {
    p00: p00,
    marginalNoclick: marginalNoclick,
    coincidence: coincidence,
    clickProbability: clickProbability,
    visibility: visibility,
    visibilityIdeal: visibilityIdeal,
    nbarPerMode: nbarPerMode,
    fisherPhi: fisherPhi,
    snlPhi: snlPhi,
    linspace: linspace,
    // truncated Fock-space engine (browser twin of spdc.fock_numpy)
    fockState: fockState,
    fockCoincidence: fockCoincidence,
    fockCoincidenceCurve: fockCoincidenceCurve,
    // exposed for the Fisher walkthrough / tests
    _outcome: { p11: p11, p20: p20, p02: p02, dp11: dp11, dp20: dp20, dp02: dp02 }
  };
})(typeof window !== "undefined" ? window : globalThis);
